const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/board-renderer.js'),'utf8'),context);
const {defaults,measure,snapPoint}=context.window.MapBoardRenderer;
const a={x:0,y:0},b={x:210,y:280};
const near=(value,expected)=>assert.ok(Math.abs(value-expected)<1e-8,`${value} != ${expected}`);
near(measure({...defaults,diagonal:'euclidean'},a,b),25);
near(measure({...defaults,diagonal:'manhattan'},a,b),35);
near(measure({...defaults,diagonal:'chebyshev'},a,b),20);
near(measure({...defaults,diagonal:'pathfinder'},a,b),25);
near(measure({...defaults,diagonal:'pathfinder'},a,{x:210,y:210}),20);
near(measure({...defaults,diagonal:'manhattan',useDistanceScale:true},a,b),25);
near(measure({...defaults,scale:100},a,{x:70,y:0}),100);
const radius=defaults.cellSize/2,h=Math.sqrt(3)*radius;
near(measure({...defaults,gridType:'hex-h'},{x:radius,y:h/2},{x:2.5*radius,y:0}),5);
near(measure({...defaults,gridType:'hex-v'},{x:-h/2,y:radius},{x:0,y:2.5*radius}),5);
near(measure({...defaults,gridType:'isometric'},a,{x:70,y:70*Math.tan(Math.PI/6)}),5);
near(measure({...defaults,gridType:'dimetric'},a,{x:70,y:35}),5);
near(measure(defaults,a,a),0);
near(snapPoint(defaults,{x:32,y:68}).x,35);
near(snapPoint(defaults,{x:32,y:68}).y,70);
const hexSnap=snapPoint({...defaults,gridType:'hex-h'},{x:radius+1,y:h/2+1});
near(hexSnap.x,radius);near(hexSnap.y,h/2);
const projectedSnap=snapPoint({...defaults,gridType:'dimetric'},{x:69,y:34});
near(projectedSnap.x,70);near(projectedSnap.y,35);
near(snapPoint({...defaults,snapToGrid:false},{x:32,y:68}).x,32);
console.log('OK - diagonales, échelle continue, hexagones et grilles projetées.');
